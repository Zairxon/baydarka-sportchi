export const FOODS = raw.map(([n, k, p, f, c, u], i) => ({ id: 'b' + i, n, k, p, f, c, u: u || null }))

// Как человек называет блюдо при поиске (гречка = гречневая каша и т. д.)
const ALIAS = {
  'Гречка, варёная': 'гречневая каша на воде каша',
  'Овсянка на воде': 'овсяная каша геркулес каша',
  'Овсянка на молоке': 'овсяная каша геркулес каша',
  'Перловка, варёная': 'перловая каша каша',
}

export const norm = s => s.toLowerCase().replace(/ё/g, 'е')

import { tt } from '../i18n/core.js'

export function searchFoods(q, custom = [], hidden = []) {
  const all = [...custom, ...FOODS].filter(f => !hidden.includes(f.n))
  const t = norm(q.trim())
  if (!t) return all.slice(0, 40)
  const words = t.split(/\s+/)
  return all
    .filter(f => words.every(w => norm(f.n).includes(w) || norm(tt(f.n)).includes(w) || (ALIAS[f.n] || '').includes(w)))
    .sort((a, b) => norm(a.n).indexOf(words[0]) - norm(b.n).indexOf(words[0]))
    .slice(0, 60)
}
